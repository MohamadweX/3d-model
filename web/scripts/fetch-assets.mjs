import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const library = path.resolve(root, "..", "3D_Asset_Library");
const manifestPath = path.join(root, "public", "manifest.json");
const localManifestPath = path.join(root, "public", "manifest.local.json");

function loadDotEnv() {
  const file = path.join(root, ".env");
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/i);
    if (!match) continue;
    const key = match[1];
    let value = match[2].trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) process.env[key] = value;
  }
}

loadDotEnv();
const base = (process.env.ASSETS_BASE || "").trim();

if (!base || base === "/assets" || !/^https?:\/\//i.test(base)) {
  throw new Error(
    "ASSETS_BASE must be a public http(s) URL (for example your R2 custom domain).\n" +
    "Set it in web/.env before running setup."
  );
}

const baseURL = new URL(base);
if (!baseURL.pathname.endsWith("/")) baseURL.pathname += "/";

function clean(rel) {
  return String(rel).replace(/^\.\.\//, "").replace(/^\.\//, "");
}

function remoteURL(rel) {
  return new URL(clean(rel), baseURL).href;
}

function safeId(id) {
  return String(id).replace(/[^a-zA-Z0-9_-]+/g, "_").slice(0, 90) || "asset";
}

const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const assets = process.env.ASSET_LIMIT
  ? manifest.assets.slice(0, Number(process.env.ASSET_LIMIT))
  : manifest.assets;

const jobs = new Map();
function addJob(rel, url) {
  const destRel = clean(rel);
  if (!destRel || !url) return;
  if (!jobs.has(destRel)) jobs.set(destRel, url);
}

for (const asset of assets) {
  addJob(asset.path, remoteURL(asset.path));
  if (asset.preview) {
    if (/^https?:\/\//i.test(asset.preview)) {
      const ext = path.extname(new URL(asset.preview).pathname) || ".webp";
      const rel = `_previews/${safeId(asset.id)}${ext}`;
      addJob(rel, asset.preview);
      asset.preview = "../" + rel;
    } else {
      addJob(asset.preview, remoteURL(asset.preview));
      asset.preview = clean(asset.preview);
    }
  }
}

let done = 0;
let skipped = 0;
let failed = 0;

async function downloadOne(rel, url, retries = 3) {
  const dest = path.join(library, rel);
  if (fs.existsSync(dest) && fs.statSync(dest).size > 0) {
    skipped += 1;
    return;
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  let lastError;
  for (let attempt = 0; attempt < retries; attempt += 1) {
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(120000) });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const buffer = Buffer.from(await response.arrayBuffer());
      if (!buffer.length) throw new Error("empty response");
      const tmp = dest + ".part";
      fs.writeFileSync(tmp, buffer);
      fs.renameSync(tmp, dest);
      done += 1;
      if ((done + skipped + failed) % 250 === 0) {
        console.log(`  downloaded ${done}, skipped ${skipped}, failed ${failed}`);
      }
      return;
    } catch (error) {
      lastError = error;
      try { fs.rmSync(dest + ".part", { force: true }); } catch {}
    }
  }
  failed += 1;
  console.error(`FAILED ${rel}: ${lastError && lastError.message}`);
}

async function runQueue(queue) {
  const entries = [...queue.entries()];
  let cursor = 0;
  async function worker() {
    while (cursor < entries.length) {
      const item = entries[cursor++];
      await downloadOne(item[0], item[1]);
    }
  }
  await Promise.all(Array.from({ length: 8 }, worker));
}

console.log(`Fetching ${jobs.size} files from ${base} into ${library}`);
await runQueue(jobs);

const linked = new Map();
for (const rel of jobs.keys()) {
  if (!rel.toLowerCase().endsWith(".gltf")) continue;
  const file = path.join(library, rel);
  if (!fs.existsSync(file)) continue;
  let gltf;
  try {
    gltf = JSON.parse(fs.readFileSync(file, "utf8"));
  } catch {
    continue;
  }
  const dir = path.posix.dirname(rel.replace(/\\/g, "/"));
  for (const key of ["buffers", "images"]) {
    for (const item of gltf[key] || []) {
      const uri = item.uri;
      if (!uri || /^data:/i.test(uri)) continue;
      const childRel = path.posix.join(dir, uri);
      linked.set(childRel, remoteURL(childRel));
    }
  }
}

if (linked.size) {
  console.log(`Fetching ${linked.size} linked glTF buffers/textures`);
  await runQueue(linked);
}

manifest.assets = assets;
manifest.manifestUrlNote = "Local manifest generated by scripts/fetch-assets.mjs";
fs.writeFileSync(localManifestPath, JSON.stringify(manifest, null, 1));

console.log(`Done: ${done} downloaded, ${skipped} already present, ${failed} failed`);
console.log(`Local manifest: ${localManifestPath}`);
if (failed) process.exitCode = 1;
